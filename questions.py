def _build_aggregates(sections: dict) -> None:
    """Добавляет в sections два автосборных раздела: "Хард марафон" (все вопросы
    вперемешку) и "Только формулы" (вопросы, где правильный ответ — формула,
    т.е. содержит "="). Вызывается один раз после того, как в sections уже
    добавлены все обычные тематические разделы — при появлении новых вопросов
    или разделов оба автораздела сами станут больше, ничего трогать не нужно."""
    sections["hard"] = {
        "title": "🔥 Хард марафон",
        "questions": [q for s in sections.values() for q in s["questions"]],
    }
    sections["formulas"] = {
        "title": "📐 Только формулы",
        "questions": [
            q
            for key, s in sections.items()
            if key != "hard"
            for q in s["questions"]
            if "=" in q["options"][q["correct"]]
        ],
    }


